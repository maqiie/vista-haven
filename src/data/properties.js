export const formatPrice = (price, type) => {
  if (type === "sale") {
    if (price >= 1000000) return `KSh ${(price / 1000000).toFixed(1)}M`;
    return `KSh ${price.toLocaleString()}`;
  }
  return `KSh ${price.toLocaleString()}/mo`;
};
